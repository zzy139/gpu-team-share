"""One-click team lifecycle: AD group and users, EFS team directory, team ECR repository, Cognito groups and users,
Slurm account and per-instance-type QOS.

``advance()`` runs one step per HTTP call. Step status is always derived from the real resources (``probe()``),
so a retry after a partial failure skips what already exists, and a step that regressed is run again.

Passwords (initial AD password and PCUI temporary password) are generated here, written to Secrets Manager and
handed to the AWS API that needs them. With PCUI_TEAMS_WELCOME_EMAIL=true, Cognito generates the PCUI temporary
password itself and e-mails it to the new user (welcome e-mail), and no PCUI password secret is written. They live only in local variables: never in the team record, the audit
log, the application log, an SSM command, an exception message or an API response.
"""

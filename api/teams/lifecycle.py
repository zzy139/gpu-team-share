STEPS = ["ad", "storage", "ecr", "cognito", "slurm"]
DONE, PENDING, IN_PROGRESS, FAILED = "done", "pending", "in_progress", "failed"
ECR_UNTAGGED_DAYS = 7
PASSWORD_LENGTH = 20
PASSWORD_SYMBOLS = "!#%+-=_"
AD_ERRORS = {"3": "adcli/ldapsearch is not installed on the head node, or the AD administrator secret is unreadable"}


class LifecycleStepError(Exception):
    def __init__(self, message, status=400):
        super().__init__(message)
        self.message = message
        self.status = status


class ADConflict(LifecycleStepError):
    def __init__(self, message):
        super().__init__(message, status=409)


def clients(config):
    region = config["region"]
    return SimpleNamespace(
        ecr=boto3.client("ecr", region_name=region),
        ds=boto3.client("ds", region_name=region),
        secrets=boto3.client("secretsmanager", region_name=region),
        cognito=boto3.client("cognito-idp", region_name=handler.REGION or region),
    )


def user_pool_id():
    return handler.USER_POOL_ID


WELCOME_EMAIL_ENV = "PCUI_TEAMS_WELCOME_EMAIL"


def welcome_email_enabled():
    """True when new PCUI users get the Cognito welcome e-mail (Lambda environment, set by the deployment)."""
    return os.getenv(WELCOME_EMAIL_ENV, "false").strip().lower() == "true"


def _code(err):
    return err.response.get("Error", {}).get("Code", "")


def _client_error_message(err):
    error = err.response.get("Error", {})
    return f"{error.get('Code', 'Error')}: {error.get('Message', '')}".strip()


def spec_members(record):
    spec = record.get("spec") or {}
    return list(spec.get("members") or [])


def spec_lead(record):
    return (record.get("spec") or {}).get("lead")


# --- passwords and secrets --------------------------------------------------------------------------------------


def generate_password(length=PASSWORD_LENGTH):
    rng = secrets.SystemRandom()
    pools = [string.ascii_uppercase, string.ascii_lowercase, string.digits, PASSWORD_SYMBOLS]
    chars = [rng.choice(pool) for pool in pools]
    chars += [rng.choice("".join(pools)) for _ in range(length - len(chars))]
    rng.shuffle(chars)
    return "".join(chars)


def ad_secret_name(config, user):
    return f"{config['secret_prefix']}{user}-password"


def pcui_secret_name(config, user):
    return f"{config['secret_prefix']}{user}-pcui-temp-password"


def _store_secret(c, config, name, team, value):
    try:
        c.secrets.create_secret(
            Name=name,
            SecretString=value,
            Description=f"Initial password generated by PCUI for team {team}",
            Tags=[{"Key": "Project", "Value": config["tags"]["Project"]}, {"Key": "Team", "Value": team}],
        )
    except ClientError as err:
        if _code(err) != "ResourceExistsException":
            raise
        c.secrets.put_secret_value(SecretId=name, SecretString=value)


def set_ad_password(config, c, record, user):
    """Generate the initial AD password, store it, then set it with ds:ResetUserPassword."""
    name = ad_secret_name(config, user)
    password = generate_password()
    _store_secret(c, config, name, record["team"], password)
    c.ds.reset_user_password(DirectoryId=config["directory_id"], UserName=user, NewPassword=password)
    del password
    if name not in record["ad_secrets"]:
        record["ad_secrets"].append(name)
    if user not in record["password_set"]:
        record["password_set"].append(user)
    put_record(config, record)


def ensure_cognito_user(config, c, record, email, user):
    """Create the PCUI user when it does not exist. An existing user that PCUI did not create is left untouched.
    Welcome e-mail on: Cognito generates the temporary password and e-mails it with the login details.
    Welcome e-mail off: a generated temporary password is stored in Secrets Manager and Cognito sends nothing.
    Returns "created" or "exists".
    """
    try:
        c.cognito.admin_get_user(UserPoolId=user_pool_id(), Username=email)
        return "exists"
    except ClientError as err:
        if _code(err) != "UserNotFoundException":
            raise
    attributes = [{"Name": "email", "Value": email}, {"Name": "email_verified", "Value": "true"}]
    if welcome_email_enabled():
        if email not in record["cognito_users_created"]:
            record["cognito_users_created"].append(email)
        put_record(config, record)  # record the intent first so a crash never leaves an untracked user
        c.cognito.admin_create_user(UserPoolId=user_pool_id(), Username=email, UserAttributes=attributes,
                                    DesiredDeliveryMediums=["EMAIL"])
        return "created"
    name = pcui_secret_name(config, user)
    if email not in record["cognito_users_created"]:
        record["cognito_users_created"].append(email)
    if name not in record["pcui_secrets"]:
        record["pcui_secrets"].append(name)
    put_record(config, record)  # record the intent first so a crash never leaves an untracked user
    password = generate_password()
    _store_secret(c, config, name, record["team"], password)
    c.cognito.admin_create_user(
        UserPoolId=user_pool_id(),
        Username=email,
        UserAttributes=attributes,
        TemporaryPassword=password,
        MessageAction="SUPPRESS",
    )
    del password
    return "created"


def ensure_cognito_group(c, group, description):
    try:
        c.cognito.get_group(GroupName=group, UserPoolId=user_pool_id())
        return "exists"
    except ClientError as err:
        if _code(err) != "ResourceNotFoundException":
            raise
    c.cognito.create_group(GroupName=group, UserPoolId=user_pool_id(), Description=description)
    return "created"


def cognito_group_users(c, group):
    """Return {email: cognito username} of the users in ``group``, or None when the group does not exist."""
    users, kwargs = {}, {"UserPoolId": user_pool_id(), "GroupName": group}
    try:
        for _ in range(50):
            resp = c.cognito.list_users_in_group(**kwargs)
            for item in resp.get("Users", []):
                attrs = {a["Name"]: a["Value"] for a in item.get("Attributes", [])}
                if attrs.get("email"):
                    users[attrs["email"].lower()] = item.get("Username")
            if not resp.get("NextToken"):
                break
            kwargs["NextToken"] = resp["NextToken"]
    except ClientError as err:
        if _code(err) == "ResourceNotFoundException":
            return None
        raise
    return users


def delete_cognito_group(c, group):
    try:
        c.cognito.delete_group(GroupName=group, UserPoolId=user_pool_id())
        return True
    except ClientError as err:
        if _code(err) == "ResourceNotFoundException":
            return False
        raise


# --- AD collision rule ------------------------------------------------------------------------------------------


def resolve_ad_user(state, email, user, link_existing, created_by_pcui=False):
    """Apply the collision rule to one lookup result. Returns "create" or "reuse"; raises ADConflict.

    * absent -> create; same mail -> reuse; different mail -> conflict;
    * no mail (legacy users such as alice) -> reuse only with ``link_existing``.
    """
    kind = (state or {}).get("state")
    if kind in (None, "absent"):
        return "create"
    if kind == "mail":
        if state.get("mail") == email.lower():
            return "reuse"
        raise ADConflict(f"AD 用户 {user} 已属于其他邮箱")
    if kind == "nomail":
        if link_existing or created_by_pcui:
            return "reuse"
        raise ADConflict(f"AD 用户 {user} 已存在但没有邮箱；确认是同一人时请勾选“关联已有 AD 用户”")
    if kind in ("exists", "created"):
        return "reuse"
    raise LifecycleStepError(f"Unexpected AD lookup result for {user}")


def _ad_error(parsed):
    code = parsed.get("error")
    return AD_ERRORS.get(code, f"AD command failed on the head node (exit {code})")


def ad_lookup(config, cluster_name, region, group, users):
    parsed = parse_ad_output(slurm.run_command(cluster_name, region, ad_command(config, group, [f"lookup:{u}" for u in users])))
    if parsed["error"]:
        raise LifecycleStepError(_ad_error(parsed))
    return parsed["users"]


def ensure_ad_members(config, c, record, cluster_name, region, members, lookups, remove=()):
    """Create missing AD users (collision rule first), add them to the team group, set initial passwords."""
    ops, to_create = ["create-group"], []
    for member in members:
        email, user = member["email"], member["user"]
        decision = resolve_ad_user(lookups.get(user), email, user, member.get("link_existing", False),
                                   user in record["ad_users_created"])
        if decision == "create":
            to_create.append(user)
            ops.append(f"create-user:{user}:{email}")
    ops += [f"add:{m['user']}" for m in members] + [f"remove:{u}" for u in remove]
    if to_create:
        record["ad_users_created"].extend(u for u in to_create if u not in record["ad_users_created"])
        put_record(config, record)  # intent first, so a created user always gets its initial password
    parsed = parse_ad_output(slurm.run_command(cluster_name, region, ad_command(config, record["ad_group"], ops)))
    if parsed["error"]:
        raise LifecycleStepError(_ad_error(parsed))
    for member in members:
        user = member["user"]
        if user in record["ad_users_created"] and user not in record["password_set"]:
            set_ad_password(config, c, record, user)
    return parsed


# --- probe ------------------------------------------------------------------------------------------------------


def _status(status, message=None):
    return {"status": status, "message": message} if message else {"status": status}


def _probe_ad(record, parsed):
    if parsed.get("error"):
        return _status(FAILED, _ad_error(parsed))
    for member in spec_members(record):
        user = member["user"]
        try:
            resolve_ad_user(parsed["users"].get(user), member["email"], user, member["link_existing"],
                            user in record["ad_users_created"])
        except LifecycleStepError as err:
            return _status(FAILED, err.message)
    if parsed["groups"].get(record["ad_group"]) != "exists":
        return _status(PENDING)
    for member in spec_members(record):
        user = member["user"]
        if parsed["users"].get(user, {}).get("state") == "absent" or parsed["members"].get(user) != "present":
            return _status(PENDING)
        if user in record["ad_users_created"] and user not in record["password_set"]:
            return _status(PENDING)
    return _status(DONE)


def resource_tags(config, team):
    return [
        {"Key": "Project", "Value": config["tags"]["Project"]},
        {"Key": "CostCenter", "Value": config["tags"]["CostCenter"]},
        {"Key": "Team", "Value": team},
    ]


def _probe_ecr(record, c):
    try:
        c.ecr.describe_repositories(repositoryNames=[record["ecr_repo"]])
    except ClientError as err:
        if _code(err) == "RepositoryNotFoundException":
            return _status(PENDING)
        return _status(FAILED, _client_error_message(err))
    return _status(DONE) if record.get("ecr_ready") else _status(PENDING)


def _probe_cognito(record, c):
    try:
        team_users = cognito_group_users(c, record["cognito_group"])
        member_users = cognito_group_users(c, record["member_group"])
    except ClientError as err:
        return _status(FAILED, _client_error_message(err))
    if team_users is None or member_users is None:
        return _status(PENDING)
    lead = spec_lead(record)
    if lead and lead not in team_users:
        return _status(PENDING)
    if any(m["email"] not in member_users for m in spec_members(record)):
        return _status(PENDING)
    return _status(DONE)


def spec_partitions(record, cluster_catalog):
    """{partition: machines} of the record's spec (instance types resolved through the cluster catalog)."""
    spec = record.get("spec") or {}
    return catalog.resolve_type_limits(cluster_catalog, spec.get("type_limits") or {})


def _probe_slurm(record, teams, qos, partitions):
    team = record["team"]
    if team not in teams or qos_name(team) not in qos:
        return _status(PENDING)
    allowed = {p: n for p, n in (partitions or {}).items() if n > 0}
    for partition, nodes in allowed.items():
        info = qos.get(type_qos_name(team, partition))
        if info is None or info["grp_tres"].get("node") != nodes:
            return _status(PENDING)
    present = {m["user"]: m for m in teams[team]["members"]}
    for member in spec_members(record):
        entry = present.get(member["user"])
        if entry is None or any(type_qos_name(team, p) not in entry["qos"] for p in allowed):
            return _status(PENDING)
    return _status(DONE)


def probe(config, record, cluster_name, region, c):
    """Return ``(steps, ctx)``: the status of every step and the data the runners reuse."""
    users = [m["user"] for m in spec_members(record)]
    sections = probe_sections(config, record["ad_group"], users, record["team_path"], record["team"])
    sections += [("ASSOC", assoc_cmd()), ("QOS", qos_cmd())]
    out = slurm.run_sections(cluster_name, region, sections)
    ad = parse_ad_output(out.get("ADPROBE", []))
    team_dir = parse_team_dir(out.get("DIRPROBE", []))
    teams, qos = parse_assoc(out.get("ASSOC", [])), parse_qos(out.get("QOS", []))
    partitions, slurm_error = None, None
    if record.get("spec"):
        try:
            partitions = spec_partitions(record, catalog.instance_catalog(cluster_name, region))
        except ValueError as err:
            slurm_error = str(err)
    steps = {
        "ad": _probe_ad(record, ad),
        "storage": _status(DONE) if team_dir_ready(team_dir, record["ad_group"]) else _status(PENDING),
        "ecr": _probe_ecr(record, c),
        "cognito": _probe_cognito(record, c),
        "slurm": _status(FAILED, slurm_error) if slurm_error else _probe_slurm(record, teams, qos, partitions),
    }
    return steps, {"ad": ad, "team_dir": team_dir, "teams": teams, "qos": qos, "partitions": partitions}


# --- step runners -----------------------------------------------------------------------------------------------


def _run_ad(config, record, cluster_name, region, c, ctx):
    ensure_ad_members(config, c, record, cluster_name, region, spec_members(record), ctx["ad"]["users"])
    return DONE


def _run_storage(config, record, cluster_name, region, c, ctx):
    path, group = record["team_path"], record["ad_group"]
    state = parse_team_dir(slurm.run_command(cluster_name, region, team_dir_command(path, group, record["team"])))
    if not team_dir_ready(state, group):
        raise LifecycleStepError(
            f"{path} is {state['dir'].get('mode')} {state['dir'].get('group')}, {path}/envs is "
            f"{state['envs'].get('mode')} {state['envs'].get('group')} and the environment directory of the team is "
            f"{state['env_team'].get('mode')} {state['env_team'].get('group')}, expected drwxrws--- / drwxrws--T / "
            f"drwxr-s--x {group}")
    return DONE


def ecr_lifecycle_policy():
    return json.dumps({"rules": [{
        "rulePriority": 1,
        "description": f"Expire untagged images after {ECR_UNTAGGED_DAYS} days",
        "selection": {"tagStatus": "untagged", "countType": "sinceImagePushed", "countUnit": "days",
                      "countNumber": ECR_UNTAGGED_DAYS},
        "action": {"type": "expire"},
    }]}, separators=(",", ":"))


def _run_ecr(config, record, cluster_name, region, c, ctx):
    """Private team repository ``<project>-<team>-envs`` (scan on push, AES256, tags Project/CostCenter/Team; the
    CodeBuild team role may only push/pull where the Team tag matches)."""
    name, tags = record["ecr_repo"], resource_tags(config, record["team"])
    try:
        c.ecr.create_repository(repositoryName=name, imageTagMutability="MUTABLE",
                                imageScanningConfiguration={"scanOnPush": True},
                                encryptionConfiguration={"encryptionType": "AES256"}, tags=tags)
    except ClientError as err:
        if _code(err) != "RepositoryAlreadyExistsException":
            raise
        arn = c.ecr.describe_repositories(repositoryNames=[name])["repositories"][0]["repositoryArn"]
        c.ecr.tag_resource(resourceArn=arn, tags=tags)
    c.ecr.put_lifecycle_policy(repositoryName=name, lifecyclePolicyText=ecr_lifecycle_policy())
    record["ecr_ready"] = True
    put_record(config, record)
    return DONE


def _run_cognito(config, record, cluster_name, region, c, ctx):
    team = record["team"]
    ensure_cognito_group(c, record["cognito_group"], f"PCUI team lead of {team}")
    ensure_cognito_group(c, record["member_group"], f"PCUI member of {team}")
    lead = spec_lead(record)
    if lead:
        ensure_cognito_user(config, c, record, lead, lead.split("@", 1)[0])
        c.cognito.admin_add_user_to_group(UserPoolId=user_pool_id(), Username=lead, GroupName=record["cognito_group"])
    for member in spec_members(record):
        ensure_cognito_user(config, c, record, member["email"], member["user"])
        c.cognito.admin_add_user_to_group(UserPoolId=user_pool_id(), Username=member["email"],
                                          GroupName=record["member_group"])
    return DONE


def _run_slurm(config, record, cluster_name, region, c, ctx):
    """Account, ``<team>-std`` (node=0), one QOS per allowed instance type, QOS lists, members, allow file."""
    team, teams, qos = record["team"], ctx["teams"], ctx["qos"]
    spec = record.get("spec")
    if not spec or ctx.get("partitions") is None:
        raise LifecycleStepError("The team specification was cleared; create the Slurm objects from the Teams page")
    allowed = {p: n for p, n in ctx["partitions"].items() if n > 0}
    commands = []
    if team not in teams:
        commands.append(create_account_cmd(team, spec["fairshare"]))
    if qos_name(team) not in qos:
        commands.append(create_std_qos_cmd(team))
    for partition, nodes in sorted(allowed.items()):
        info = qos.get(type_qos_name(team, partition))
        if info is None:
            commands.append(create_type_qos_cmd(team, partition, nodes))
        elif info["grp_tres"].get("node") != nodes:
            commands.append(set_type_qos_cmd(team, partition, nodes))
    present = {m["user"] for m in (teams.get(team) or {}).get("members", [])}
    commands += grant_qos_cmds(team, allowed, with_users=bool(present))
    commands += [add_member_cmd(team, m["user"], allowed) for m in spec_members(record) if m["user"] not in present]
    commands.append(gen_type_quota_argv())
    slurm.run_writes(cluster_name, region, commands)
    return DONE


RUNNERS = {"ad": _run_ad, "storage": _run_storage, "ecr": _run_ecr, "cognito": _run_cognito, "slurm": _run_slurm}


def step_list(steps):
    return [{"id": step, **steps[step]} for step in STEPS]


def run_step(step, config, record, cluster_name, region, c, ctx):
    """Run one step and return its status dict. Errors become a safe ``failed`` message and are audited."""
    try:
        status = RUNNERS[step](config, record, cluster_name, region, c, ctx)
    except LifecycleStepError as err:
        message = err.message
    except SlurmCommandError as err:
        message = err.message
    except ClientError as err:
        message = _client_error_message(err)
    else:
        audit(f"lifecycle_{step}", cluster_name, record["team"], {"step": step}, "success")
        return _status(status)
    logger.warning(f"Team lifecycle step {step} failed for {record['team']}: {message}")
    audit(f"lifecycle_{step}", cluster_name, record["team"], {"step": step}, "failure", error=message)
    return _status(FAILED, message)


def advance(config, record, cluster_name, region, c):
    """Probe, run the first step that is not done, persist and return every step status."""
    steps, ctx = probe(config, record, cluster_name, region, c)
    for step in STEPS:
        status = steps[step]["status"]
        if status == DONE:
            continue
        if status == PENDING:
            steps[step] = run_step(step, config, record, cluster_name, region, c, ctx)
        break
    complete = all(steps[s]["status"] == DONE for s in STEPS)
    if complete and record["state"] != "active":
        record["state"] = "active"
        record["spec"] = None
        put_record(config, record)
        audit("lifecycle_complete", cluster_name, record["team"], {}, "success")
    return {"team": record["team"], "state": record["state"], "steps": step_list(steps), "complete": complete}

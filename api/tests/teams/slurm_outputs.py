def sections(**named):
    """Render outputs the way the head node prints them for a join_commands() call."""
    lines = []
    for name, body in named.items():
        lines.append(f"@@{name}")
        lines.extend(line.strip() for line in body.splitlines() if line.strip())
    return "\n".join(lines)
